function g = evaluateExample02(X)
%EVALUATEEXAMPLE02 Quadratic limit-state function, paper Eq. (25).
x1=X(:,1); x2=X(:,2); x3=X(:,3); x4=X(:,4);
g = 1.1 - 0.00115*x1.*x2 + 0.00157*x2.^2 + 0.00117*x1.^2 ...
    + 0.0135*x2.*x3 - 0.0705*x2 - 0.00534*x1 ...
    - 0.0149*x1.*x3 - 0.0611*x2.*x4 + 0.0717*x1.*x4 ...
    - 0.226*x3 + 0.0333*x3.^2 - 0.558*x3.*x4 ...
    + 0.998*x4 - 1.339*x4.^2;
end
